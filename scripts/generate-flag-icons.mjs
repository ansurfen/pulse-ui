function sanitizeSvg(svg, countryId, numeric) {
  const prefix = `${numeric}_svg__`;
  let out = svg.replaceAll(prefix, `flag_${countryId.replace(/-/g, "_")}_`);

  // Some flagpack assets reference masks without defs (e.g. South Korea).
  out = out.replace(/\s*mask="url\(#([^"]+)\)"/g, "");

  return out;
}

/** Light gray so white-heavy flags stay visible on white UI backgrounds. */
const LIGHT_FLAG_SURFACE = "#E8EAED";

function tuneSvgForDisplay(svg, countryId) {
  if (countryId !== "japan" && countryId !== "south-korea") {
    return svg;
  }

  return svg.replace(/fill="#F7FCFF"/g, `fill="${LIGHT_FLAG_SURFACE}"`).replace(/fill="#FEFFFF"/g, `fill="${LIGHT_FLAG_SURFACE}"`);
}

function escapeTemplate(value) {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const entries = [];

for (const country of countries) {
  const url = `https://cdn.jsdelivr.net/npm/flagpack-core@2.0.0/lib/flags/l/${country.numeric}.svg`;
  const response = await fetch(url);

  if (!response.ok) {
    console.error(`Failed to download ${country.id}: ${response.status} ${url}`);
    process.exit(1);
  }

  const svg = tuneSvgForDisplay(sanitizeSvg(await response.text(), country.id, country.numeric), country.id);
  entries.push({ ...country, svg });
  console.log(`Downloaded ${country.id}`);
}

const body = entries
  .map(
    (entry) => `  "${entry.id}": {
    baseColor: "${entry.baseColor}",
    svg: \`${escapeTemplate(entry.svg)}\`
  }`
  )
  .join(",\n");

const output = `// Auto-generated by scripts/generate-flag-icons.mjs — do not edit manually.
// Flag artwork from flagpack-core (MIT): https://github.com/Yummygum/flagpack-core
import type { CountryId } from "../CountryMap/types";

export type FlagSvgDefinition = {
  svg: string;
  baseColor: string;
};

export const flagSvgDefinitions = {
${body}
} as const satisfies Record<CountryId, FlagSvgDefinition>;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, output, "utf8");
console.log(`Wrote ${outFile}`);
